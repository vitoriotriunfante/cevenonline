/**
 * Resolve a busca pelo nome popular, marca ou produto
 */
export function resolverIndustria(termoBuscado) {
  if (!termoBuscado) return null;
  const termoLimpo = termoBuscado.toLowerCase().trim();

  // 1. Busca direta no mapa
  if (DE_PARA_INDUSTRIAS[termoLimpo]) {
    return DE_PARA_INDUSTRIAS[termoLimpo];
  }

  // 2. Busca por termos contidos
  for (const [apelido, razaoSocial] of Object.entries(DE_PARA_INDUSTRIAS)) {
    if (termoLimpo === apelido || termoLimpo.includes(apelido) || apelido.includes(termoLimpo)) {
      return razaoSocial;
    }
  }

  return termoLimpo.toUpperCase();
}
